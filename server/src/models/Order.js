import mongoose from "mongoose";

const itemSchema=new mongoose.Schema({
  productId:{type:mongoose.Schema.Types.ObjectId,ref:"Product",required:true},
  name:{type:String,required:true,trim:true,maxlength:120},
  category:{type:String,required:true,trim:true,maxlength:80},
  quantity:{type:Number,required:true,min:1},
  packetQuantity:{type:Number,min:1},
  weightCalculationMethod:{type:String,enum:["BUNDLE","PIECE"]},
  piecesPerBundle:{type:Number,min:1},
  bundleWeightGrams:{type:Number,min:0.000001},
  piecesPerKg:{type:Number,min:1},
  unitWeightGrams:{type:Number,min:0.000001},
  unitLabel:{type:String,enum:["bundle","piece"]},
  piecesPerPacket:{type:Number,min:1},
  packetWeightGrams:{type:Number,min:1},
  packetPrice:{type:Number,min:0.01},
  quantityWeightG:{type:Number,min:0.000001},
  lineTotal:{type:Number,required:true,min:0},
  imageUrl:{type:String,default:""}
},{_id:false});

const schema=new mongoose.Schema({
  businessId:{type:mongoose.Schema.Types.ObjectId,ref:"Business",required:true,index:true},
  customerId:{type:mongoose.Schema.Types.ObjectId,ref:"Customer",default:null},
  orderNumber:{type:String,required:true,unique:true,index:true},
  items:{type:[itemSchema],required:true,validate:value=>value.length>0},
  customerName:{type:String,required:true,trim:true,maxlength:100},
  customerPhone:{type:String,required:true,trim:true,maxlength:20},
  deliveryAddress:{type:String,required:true,trim:true,maxlength:500},
  deliveryPincode:{type:String,default:"",match:/^$|^\d{6}$/},
  deliveryDistrict:{type:String,default:"",trim:true,maxlength:100},
  deliveryState:{type:String,default:"",trim:true,maxlength:100},
  deliveryZoneName:{type:String,default:"",trim:true,maxlength:60},
  deliveryRegionSnapshot:{type:mongoose.Schema.Types.Mixed,default:null},
  billSnapshot:{type:mongoose.Schema.Types.Mixed,default:null},
  postalCategory:{type:String,enum:["LOCAL","WITHIN_STATE","ZONE_METRO","OTHER_STATES"]},
  warehouseSnapshot:{type:mongoose.Schema.Types.Mixed},
  shippingServiceId:{type:String,default:""},
  shippingQuoteSnapshot:{type:mongoose.Schema.Types.Mixed,default:null},
  postalClassificationSnapshot:{type:mongoose.Schema.Types.Mixed},
  tariffSnapshot:{type:mongoose.Schema.Types.Mixed},
  courierProvider:{type:String,default:""},
  tariffName:{type:String,default:""},
  tariffVersion:{type:String,default:""},
  tariffEffectiveDate:Date,
  totalPieces:{type:Number,min:1},
  totalWeightGrams:{type:Number,min:1},
  chargeableWeightGrams:{type:Number,min:1},
  productTotalInr:{type:Number,min:0},
  deliveryChargeInr:{type:Number,min:0},
  gstRatePercent:{type:Number,min:0,max:100},
  gstAmountInr:{type:Number,min:0},
  grandTotalInr:{type:Number,min:0},
  totalWeightG:{type:Number,required:true,min:1000},
  subtotalInr:{type:Number,required:true,min:0},
  deliveryFeeInr:{type:Number,required:true,min:0},
  totalInr:{type:Number,required:true,min:0},
  paymentQrSnapshot:{type:String,default:""},
  paymentQrSnapshotPublicId:{type:String,default:""},
  upiIdSnapshot:{type:String,default:""},
  paymentInstructionsSnapshot:{type:String,default:""},
  status:{type:String,enum:["PLACED","ACCEPTED","REJECTED"],default:"PLACED",index:true},
  unreadBusinessMessages:{type:Number,default:0,min:0},
  unreadCustomerMessages:{type:Number,default:0,min:0},
  paymentStatus:{type:String,enum:["UNPAID","PROOF_SUBMITTED","VERIFIED","REJECTED"],default:"UNPAID"},
  paymentUtr:{type:String,default:"",trim:true,maxlength:40},
  paymentProofPublicId:{type:String,default:"",select:false},
  paymentVerifiedAt:Date,
  paymentVerifiedBy:{type:mongoose.Schema.Types.ObjectId,ref:"User"},
  businessArchivedAt:{type:Date,default:null},
  businessArchivedBy:{type:mongoose.Schema.Types.ObjectId,ref:"User",default:null},
  customerArchivedAt:{type:Date,default:null},
  customerAccessTokenHash:{type:String,required:true,select:false}
},{timestamps:true});

schema.index({businessId:1,businessArchivedAt:1,createdAt:-1});
schema.index({customerId:1,businessId:1,customerArchivedAt:1,createdAt:-1});
export default mongoose.model("Order",schema);
