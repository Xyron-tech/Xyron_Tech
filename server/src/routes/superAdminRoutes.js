import {Router} from "express";
import {deleteBusiness,listApplications,listCustomerRecoveryRequests,rejectBusiness,reviewApplication,updateBusinessPlan,updateCustomerRecoveryRequest} from "../controllers/superAdminController.js";
import {broadcastToBusinesses,getSuperAdminInboxCounts,getSuperAdminSupport,listSupportBusinesses,listSuperAdminSupport,replySuperAdminSupport,updateSupportStatus} from "../controllers/supportController.js";
import {asyncHandler} from "../middleware/asyncHandler.js";
import {requireAuth,requireRole} from "../middleware/auth.js";
import {listSuperAdminTestimonials,updateTestimonialModeration} from "../controllers/testimonialController.js";

const r=Router();
r.use(requireAuth,requireRole("SUPER_ADMIN"));
r.get("/applications",asyncHandler(listApplications));
r.post("/applications/:id/:decision",asyncHandler(reviewApplication));
r.patch("/businesses/:id/plan",asyncHandler(updateBusinessPlan));
r.get("/testimonials",asyncHandler(listSuperAdminTestimonials));
r.patch("/testimonials/:id",asyncHandler(updateTestimonialModeration));
r.post("/businesses/:id/reject",asyncHandler(rejectBusiness));
r.delete("/businesses/:id",asyncHandler(deleteBusiness));
r.get("/customer-recovery-requests",asyncHandler(listCustomerRecoveryRequests));
r.patch("/customer-recovery-requests/:id",asyncHandler(updateCustomerRecoveryRequest));
r.get("/businesses",asyncHandler(listSupportBusinesses));
r.get("/inbox-counts",asyncHandler(getSuperAdminInboxCounts));
r.get("/support",asyncHandler(listSuperAdminSupport));
r.get("/support/:id",asyncHandler(getSuperAdminSupport));
r.post("/support/broadcast",asyncHandler(broadcastToBusinesses));
r.post("/support/:id/messages",asyncHandler(replySuperAdminSupport));
r.patch("/support/:id/status",asyncHandler(updateSupportStatus));
export default r;
